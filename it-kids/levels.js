// Повторить кусочек узора n раз: rep(['🔴','🔵'], 3) → 🔴🔵🔴🔵🔴🔵
function rep(unit, times) {
  const out = [];
  for (let i = 0; i < times; i++) out.push(...unit);
  return out;
}

// Таблица «номер буквы в алфавите → буква» для нужных букв
const RU_ALPHABET = 'АБВГДЕЁЖЗИЙКЛМНОПРСТУФХЦЧШЩЪЫЬЭЮЯ';
function numTable(letters) {
  return [...new Set(letters.split(''))].map(ch => [String(RU_ALPHABET.indexOf(ch) + 1), ch]);
}

const MORSE = {
  А: '·−', Б: '−···', Д: '−··', Е: '·', И: '··', К: '−·−', М: '−−',
  Н: '−·', О: '−−−', Р: '·−·', С: '···', Т: '−'
};
function morseTable(letters) {
  return [...new Set(letters.split(''))].map(ch => [MORSE[ch], ch]);
}

